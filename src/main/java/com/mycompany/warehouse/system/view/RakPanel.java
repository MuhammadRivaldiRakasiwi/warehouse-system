    private void setupSearch() {
        final String placeholder = "Cari data..";
        txtSearch.setText(placeholder);
        txtSearch.setForeground(new java.awt.Color(150, 150, 150));

        txtSearch.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                if (txtSearch.getText().equals(placeholder)) {
                    txtSearch.setText("");
                    txtSearch.setForeground(java.awt.Color.BLACK);
                }
            }
            @Override
            public void focusLost(java.awt.event.FocusEvent e) {
                if (txtSearch.getText().isEmpty()) {
                    txtSearch.setText(placeholder);
                    txtSearch.setForeground(new java.awt.Color(150, 150, 150));
                }
            }
        });

        txtSearch.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
            @Override public void insertUpdate(javax.swing.event.DocumentEvent e) { filterTable(); }
            @Override public void removeUpdate(javax.swing.event.DocumentEvent e) { filterTable(); }
            @Override public void changedUpdate(javax.swing.event.DocumentEvent e) { filterTable(); }
        });
    }

    private void filterTable() {
        String keyword = txtSearch.getText();
        if (keyword.equals("Cari data..")) keyword = "";
        if (rowSorter != null) {
            if (keyword.trim().isEmpty()) {
                rowSorter.setRowFilter(null);
            } else {
                rowSorter.setRowFilter(RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(keyword)));
            }
        }
    }

    private void setupTable() {
        jTable1.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int viewRow = jTable1.getSelectedRow();
                if (viewRow < 0) return;
                int row = jTable1.convertRowIndexToModel(viewRow);
                if (row >= 0 && row < locationIds.size()) {
                    selectedId = locationIds.get(row);
                    javax.swing.table.TableModel m = jTable1.getModel();
                    // columns: 0=Kode Lokasi, 1=Zona, 2=Rak, 3=Level Rak, 4=Kapasitas
                    txtZona.setText(String.valueOf(m.getValueAt(row, 1)));
                    txtRak.setText(String.valueOf(m.getValueAt(row, 2)));
                    txtLevelRak.setText(String.valueOf(m.getValueAt(row, 3)));
                    txtKapasitas.setText(String.valueOf(m.getValueAt(row, 4)));
                    btnSimpan.setText("Update Data");
                }
            }
        });
    }

