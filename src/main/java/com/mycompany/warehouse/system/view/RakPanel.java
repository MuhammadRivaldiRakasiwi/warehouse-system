    public final void loadData() {
        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Kode Lokasi", "Zona", "Rak", "Level Rak", "Kapasitas"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };

        locationIds.clear();
        try (Connection conn = DatabaseConfig.getConnection()) {
            String sql = "SELECT id, kode_lokasi, zona, rak, level_rak, kapasitas_maksimum "
                    + "FROM locations WHERE status_aktif = 1 ORDER BY id ASC";
            ResultSet rs = conn.createStatement().executeQuery(sql);
            while (rs.next()) {
                locationIds.add(rs.getInt("id"));
                model.addRow(new Object[]{
                    rs.getString("kode_lokasi"),
                    rs.getString("zona"),
                    rs.getString("rak"),
                    rs.getString("level_rak"),
                    rs.getInt("kapasitas_maksimum")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }

        jTable1.setModel(model);
        rowSorter = new TableRowSorter<>(model);
        jTable1.setRowSorter(rowSorter);

        jTable1.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);

        // Force warna teks hitam dengan custom renderer
        javax.swing.table.DefaultTableCellRenderer cellRenderer = new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {
                super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
                setForeground(java.awt.Color.BLACK);
                setBackground(isSelected ? new java.awt.Color(184, 207, 229) : java.awt.Color.WHITE);
                setBorder(javax.swing.BorderFactory.createEmptyBorder(4, 8, 4, 8));
                return this;
            }
        };
        jTable1.setDefaultRenderer(Object.class, cellRenderer);

        // Set tinggi scrollPane = header + (rowCount × rowHeight) + 2px buffer
        int headerHeight = jTable1.getTableHeader().getPreferredSize().height;
        int contentHeight = model.getRowCount() * jTable1.getRowHeight();
        int minHeight = headerHeight + jTable1.getRowHeight();
        int finalHeight = Math.max(minHeight, headerHeight + contentHeight + 2);
        jScrollPane1.setPreferredSize(new java.awt.Dimension(0, finalHeight));
        jPanelTable.revalidate();
        jPanelTable.repaint();

        labelInfo.setText("Total " + model.getRowCount() + " data lokasi.");
    }

    private String generateKodeLokasi(String zona, String rak, String levelRak) {
        // Format: LOC-ZONA-RAK-LEVEL
        String z = zona.trim().toUpperCase().replaceAll("\\s+", "");
        String r = rak.trim().toUpperCase().replaceAll("\\s+", "");
        String l = levelRak.trim().toUpperCase().replaceAll("\\s+", "");
        return "LOC-" + z + "-" + r + "-" + l;
    }

    private void simpanData() {
        String zona = txtZona.getText().trim();
        String rak = txtRak.getText().trim();
        String levelRak = txtLevelRak.getText().trim();
        String kapasitas = txtKapasitas.getText().trim();

        if (zona.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Zona tidak boleh kosong!");
            txtZona.requestFocus();
            return;
        }

        try (Connection conn = DatabaseConfig.getConnection()) {
            if (selectedId == -1) {
                String kodeLokasi = generateKodeLokasi(zona, rak, levelRak);
                String sql = "INSERT INTO locations (kode_lokasi, zona, rak, level_rak, kapasitas_maksimum, status_aktif, created_at, updated_at) "
                        + "VALUES (?, ?, ?, ?, ?, 1, NOW(), NOW())";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setString(1, kodeLokasi);
                ps.setString(2, zona);
                ps.setString(3, rak);
                ps.setString(4, levelRak);
                ps.setInt(5, kapasitas.isEmpty() ? 0 : Integer.parseInt(kapasitas));
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data rak berhasil disimpan!");
            } else {
                String sql = "UPDATE locations SET zona=?, rak=?, level_rak=?, kapasitas_maksimum=?, updated_at=NOW() WHERE id=?";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setString(1, zona);
                ps.setString(2, rak);
                ps.setString(3, levelRak);
                ps.setInt(4, kapasitas.isEmpty() ? 0 : Integer.parseInt(kapasitas));
                ps.setInt(5, selectedId);
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data rak berhasil diupdate!");
            }
            clearForm();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Kapasitas harus berupa angka!");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage());
        }
    }

    private void hapusData() {
        if (selectedId == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data rak yang ingin dihapus dari tabel!");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this,
                "Apakah Anda yakin ingin menghapus rak ini?",
                "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try (Connection conn = DatabaseConfig.getConnection()) {
                String sql = "UPDATE locations SET status_aktif = 0, updated_at = NOW() WHERE id = ?";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setInt(1, selectedId);
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data rak berhasil dihapus!");
                clearForm();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage());
            }
        }
    }

    private void clearForm() {
        txtZona.setText("");
        txtRak.setText("");
        txtLevelRak.setText("");
        txtKapasitas.setText("");
        selectedId = -1;
        btnSimpan.setText("Simpan Data");
        txtZona.requestFocus();
        loadData();
    }

